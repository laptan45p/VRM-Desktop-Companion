const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('companion', {
  relationship:(operation,value)=>ipcRenderer.invoke('relationship',operation,value),
  confess:()=>ipcRenderer.invoke('confess'),
  state:()=>ipcRenderer.invoke('state'),
  save:s=>ipcRenderer.invoke('save',s),
  chooseSpeaker:()=>ipcRenderer.invoke('choose-speaker'),
  voiceState:(id,phase,error)=>ipcRenderer.invoke('voice-state',id,phase,error),
  chooseMotions:()=>ipcRenderer.invoke('choose-motions'),
  motionList:()=>ipcRenderer.invoke('motion-list'),
  motionData:name=>ipcRenderer.invoke('motion-data',name),
  expressionCatalog:()=>ipcRenderer.invoke('expression-catalog'),
  mascotReady:()=>ipcRenderer.invoke('mascot-ready'),
  expressionReady:(modelPath,names)=>ipcRenderer.invoke('expression-ready',modelPath,names),
  previewExpression:(modelPath,name,weight)=>ipcRenderer.invoke('expression-preview',modelPath,name,weight),
  keyStatus:s=>ipcRenderer.invoke('key-status',s),
  saveKey:(s,key)=>ipcRenderer.invoke('key-save',s,key),
  deleteKey:s=>ipcRenderer.invoke('key-delete',s),
  llamaStatus:()=>ipcRenderer.invoke('llama-status'),
  chooseLlamaFile:kind=>ipcRenderer.invoke('choose-llama-file',kind),
  startLlama:()=>ipcRenderer.invoke('llama-start'),
  stopLlama:()=>ipcRenderer.invoke('llama-stop'),
  models:s=>ipcRenderer.invoke('models',s),
  chooseVRM:()=>ipcRenderer.invoke('choose-vrm'),
  vrm:()=>ipcRenderer.invoke('vrm'),
  send:text=>ipcRenderer.invoke('chat',text),
  cancel:()=>ipcRenderer.invoke('cancel'),
  clear:()=>ipcRenderer.invoke('clear'),
  hit:v=>ipcRenderer.invoke('hit',v),
  touch:(region,gesture)=>ipcRenderer.invoke('touch',region,gesture),
  drag:(phase,x,y)=>ipcRenderer.invoke('drag',phase,x,y),
  zoom:delta=>ipcRenderer.invoke('zoom',delta),
  orientation:angles=>ipcRenderer.invoke('orientation',angles),
  bubbleSize:h=>ipcRenderer.invoke('bubble-size',h),
  modelStatus:text=>ipcRenderer.invoke('model-status',text),
  action:name=>ipcRenderer.invoke('action',name),
  onUpdate:fn=>{const listener=(_e,data)=>fn(data);ipcRenderer.on('update',listener);return()=>ipcRenderer.removeListener('update',listener);},
});


